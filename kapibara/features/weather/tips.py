STORM_CODES = {95, 96, 99}
SNOW_CODES = {71, 73, 75}
RAIN_CODES = {51, 53, 55, 61, 63, 65, 80, 81, 82}
HEAVY_RAIN_CODES = {65, 81, 82}
FOG_CODES = {45, 48}
STRONG_WIND = 35        # км/ч: Open-Meteo отдаёт windspeed_10m в км/ч


def _pick(pool: list[str], day: date) -> str:
    return pool[day.toordinal() % len(pool)]


def clothes_tip(temp: int, feels: int | None = None, code: int = 0,
                wind: float = 0, precip: float = 0, day: date | None = None) -> str:
    """Один совет. Главное — как ощущается (feels), а не градусник; поверх —
    гроза, снег, дождь, сильный ветер. Только температура — тоже работает."""
    day = day or date.today()
    f = temp if feels is None else feels
    cold = f < 8
    if code in (96, 99):
        return _pick(_HAIL, day)
    if code in STORM_CODES:
        return _pick(_STORM, day)
    if code == 75 or (code in SNOW_CODES and wind >= STRONG_WIND):
        return _pick(_SNOW_HEAVY, day)
    if code in SNOW_CODES or (precip > 0 and f <= 0):
        return _pick(_SNOW, day)
    if code in HEAVY_RAIN_CODES or precip >= 5:
        return _pick(_RAIN_HEAVY, day)
    if code in RAIN_CODES or precip > 0.2:
        return _pick(_RAIN_COLD if cold else _RAIN_WARM, day)
    if code in FOG_CODES and f < 15:
        return _pick(_FOG, day)
    if wind >= STRONG_WIND and f < 22:
        return _pick(_WIND_COLD if cold else _WIND_WARM, day)
    if feels is not None and temp - feels >= 5 and f < 15:
        return _pick(_FEELS_GAP, day)
    for limit, pool in _BY_FEELS:
        if f < limit:
            return _pick(pool, day)
    return _pick(_BY_FEELS[-1][1], day)

"""Институт группы по шифру (5.100.3, рейтинг групп): «УИБО-03-24» → ИТУ.

Первая буква шифра — институт (открытые расписания МИРЭА: ИКБО, ИНБО — ИИТ;
КМБО — ИИИ; БСБО, БИСО — ИКБ; РИБО — ИРИ; УИБО — ИТУ; ЭФБО — ИПТИП; ХББО —
ИТХТ). Таблицу проверяет Никита: /institutes в боте — все шифры групп из
справочника расписания и к какому институту они попали. Исключения — в
PREFIXES (шифр целиком важнее буквы). Не похоже на шифр группы вуза
(колледж, аспирантура) — института нет, группа только в общем рейтинге.
"""

import re

INSTITUTES = {
    "ИИТ": "Институт информационных технологий",
    "ИИИ": "Институт искусственного интеллекта",
    "ИКБ": "Институт кибербезопасности и цифровых технологий",
    "ИРИ": "Институт радиоэлектроники и информатики",
    "ИТУ": "Институт технологий управления",
    "ИПТИП": "Институт перспективных технологий и индустриального программирования",
    "ИТХТ": "Институт тонких химических технологий имени М. В. Ломоносова",
}

LETTERS = {"И": "ИИТ", "К": "ИИИ", "Б": "ИКБ", "Р": "ИРИ", "У": "ИТУ", "Э": "ИПТИП", "Х": "ИТХТ"}

# Шифр целиком → институт, когда буква обманывает (дополняется по проверке).
PREFIXES: dict[str, str] = {}

_GROUP = re.compile(r"^([А-ЯЁ]{4})-\d{2}-\d{2}")


def prefix(name: str) -> str:
    m = _GROUP.match((name or "").strip().upper())
    return m.group(1) if m else ""


def of(name: str) -> str:
    """Код института («ИТУ») или '' — не знаем."""
    p = prefix(name)
    if not p:
        return ""
    return PREFIXES.get(p) or LETTERS.get(p[0], "")


def table(names) -> list[dict]:
    """Шифры из списка названий групп: [{prefix, institute, groups, sample}] —
    для проверки (/institutes)."""
    out: dict[str, dict] = {}
    for n in names:
        p = prefix(n)
        if not p:
            continue
        row = out.setdefault(p, {"prefix": p, "institute": of(n), "groups": 0, "sample": n})
        row["groups"] += 1
    return sorted(out.values(), key=lambda r: (r["institute"] or "я", r["prefix"]))

"""Подбор лекций: сокращения («ООП», «БД», «матан»), латинские аббревиатуры
(SQL, ERP) и падежи («базами» ↔ «база») находят нужную лекцию."""
from kapibara.features.lectures import picker as lp

CTX = "\n\n".join([
    "=== Лекция 1. Введение ===\nОрганизационные вопросы курса и правила аттестации студентов группы.",
    "=== Лекция 2. Объектно-ориентированное программирование ===\nКлассы, объекты, наследование, полиморфизм.",
    "=== Лекция 3. Реляционные базы данных ===\nТаблицы, ключи, нормализация; язык запросов SQL и SELECT.",
    "=== Лекция 4. Математический анализ ===\nПределы, производные, интегралы функций.",
    "=== Лекция 5. Корпоративные системы ===\nКлассы систем ERP и CRM на предприятии.",
] + [f"=== Лекция {i}. Прочее ===\n{'наполнитель ' * 4000}" for i in range(6, 12)])


def first(query):
    out = lp.pick(CTX, query, budget=3000, min_score=1)
    return out.split("\n", 1)[0] if out else ""


def test_abbreviations_find_lecture():
    assert "Объектно" in first("что такое ООП?")
    assert "базы данных" in first("как устроена БД")
    assert "Математический" in first("помоги с матаном")


def test_latin_acronyms_kept():
    assert "базы данных" in first("запрос на SQL")
    assert "Корпоративные" in first("чем ERP отличается от CRM")


def test_cases_match():
    assert "базы данных" in first("нормализация в базах")
    assert lp._stem("база") == lp._stem("базами") == lp._stem("базы")


def test_expand_only_whole_words():
    assert lp.expand("пример") == "пример"               # «пр» внутри слова не расшифровывается
    assert "практическая" in lp.expand("пр 3 по ООП")

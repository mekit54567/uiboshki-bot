DOCS = {"consent": CONSENT, "privacy": PRIVACY}


def doc(name: str) -> dict:
    """Текст с подстановками — для страницы и для /api/legal/<имя>."""
    import privacy
    values = {"OPERATOR": privacy.OPERATOR, "CONTACT": privacy.CONTACT,
              "INACTIVE_DAYS": str(privacy.INACTIVE_DAYS), "SOLVER_DAYS": str(privacy.SOLVER_DAYS),
              "ANSWER_DAYS": str(privacy.ANSWER_DAYS), **privacy.backup_texts()}

    def fill(text: str) -> str:
        for k, v in values.items():
            text = text.replace("{" + k + "}", v)
        return text

    src = DOCS[name]
    sections = [{"title": s["title"],
                 "blocks": [{"ul": [fill(i) for i in b]} if isinstance(b, list) else {"p": fill(b)}
                            for b in s["blocks"]]}
                for s in src["sections"]]
    return {"name": name, "title": src["title"], "version": privacy.VERSION, "date": privacy.DATE,
            "lead": fill(src["lead"]), "sections": sections}

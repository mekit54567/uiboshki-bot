from offer_text import OFFER  # noqa: E402 — оферта подписки, своя версия (offer_text.py)

DOCS = {"consent": CONSENT, "privacy": PRIVACY, "offer": OFFER, "rules": RULES, "rating_all": RATING_ALL}


def payment_names() -> str:
    """Касса, которая правда включена (billing.provider); не включена — обе возможные."""
    import billing
    names = {"yookassa": "ООО НКО «ЮMoney» (ЮKassa, Россия)", "robokassa": "ООО «Робокасса» (Россия)"}
    return names.get(billing.provider(configured_only=True)) or " или ".join(names.values())


def doc(name: str) -> dict:
    """Текст с подстановками — для страницы и для /api/legal/<имя>."""
    import privacy
    import ugc
    values = {"OPERATOR": privacy.OPERATOR, "CONTRACTOR": privacy.contractor(), "CONTACT": privacy.CONTACT,
              "INACTIVE_DAYS": str(privacy.INACTIVE_DAYS), "SOLVER_DAYS": str(privacy.SOLVER_DAYS),
              "ANSWER_DAYS": str(privacy.ANSWER_DAYS), "ERASE_DAYS": str(privacy.ERASE_DAYS),
              "ERASE_PHRASE": privacy.ERASE_PHRASE, "PAYMENT": payment_names(),
              "DISPUTE_DAYS": str(ugc.DISPUTE_DAYS),
              **privacy.backup_texts(), **privacy.hosting_texts()}

    def fill(text: str) -> str:
        for k, v in values.items():
            text = text.replace("{" + k + "}", v)
        return text

    def blocks(items: list) -> list:
        return [{"ul": [fill(i) for i in b]} if isinstance(b, list) else {"p": fill(b)}
                for b in items]

    src = DOCS[name]
    sections = []
    for s in src["sections"]:
        sec = {"title": s["title"], "blocks": blocks(s["blocks"])}
        if s.get("short"):
            sec["short"] = blocks(s["short"])
        if s.get("sheet"):           # раздел на листе согласия «Показывать меня всем» (rating.dart)
            sec["sheet"] = True
        sections.append(sec)
    out = {"name": name, "title": src["title"], "version": src.get("version", privacy.VERSION),
           "date": src.get("date", privacy.DATE),
           "lead": fill(src["lead"]), "sections": sections}
    if "lead_short" in src:
        out["lead_short"] = fill(src["lead_short"])
    return out
